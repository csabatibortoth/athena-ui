// Writes docs/styling.md: the tokens and, for every group of rules in default/style.css, the classes and variables it uses.
// Run it with `npm run docs`. The test suite checks that the file is up to date.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const style = readFileSync(join(root, "src/res/themes/default/style.css"), "utf8").replace(/\r\n/g, "\n");
const tokens = readFileSync(join(root, "src/res/themes/tokens.css"), "utf8").replace(/\r\n/g, "\n");

export function buildStylingDocs() {
    // groups: a top-level comment line "/* Title */" starts one
    const groups = [];
    let current = { title: "General", css: "" };
    for (const block of style.split(/\n(?=\/\* [^\n]*\*\/\n)/)) {
        const match = /^\/\* ([^\n]*?) \*\/\n/.exec(block);
        if (match && !match[1].startsWith("Default Athena") && !match[1].startsWith("The doubled")) {
            groups.push(current);
            current = { title: match[1], css: "" };
        }
        current.css += block;
    }
    groups.push(current);

    const lines = [
        "# Styling reference",
        "",
        "Generated by `npm run docs` from `src/res/themes/default/style.css` and `tokens.css`. Do not edit by hand.",
        "",
        "All Athena UI rules are in the cascade layer `athena`: a plain rule of your application (not in a layer) always wins, whatever its specificity.",
        "Start with the tokens, they cover most of what people want to change.",
        "",
        "## Tokens",
        "",
        "| Variable | Default (light) |",
        "| --- | --- |"
    ];
    const rootBlock = /:root \{([\s\S]*?)\n\}/.exec(tokens)[1];
    for (const [, name, value] of rootBlock.matchAll(/(--[\w-]+):\s*([^;]+);/g)) lines.push(`| \`${name}\` | \`${value.trim()}\` |`);
    lines.push("", "Dark colours: set `data-mode=\"dark\"` on `<html>` (or let `createThemeManager` do it); without the attribute the system decides. Themes: see `appearance.css`.", "", "## Components", "",
        "| Group of rules | Classes | Variables it reads |", "| --- | --- | --- |");
    for (const group of groups) {
        const code = group.css.replace(/\/\*[\s\S]*?\*\//g, "").replace(/@import[^;]*;/g, "");
        const classes = [...new Set([...code.matchAll(/\.([a-zA-Z][\w-]*)/g)].map(m => m[1]))].filter(name => !/^\d/.test(name)).sort();
        const variables = [...new Set([...code.matchAll(/var\((--[\w-]+)/g)].map(m => m[1]))].sort();
        if (!classes.length && !variables.length) continue;
        lines.push(`| ${group.title.replace(/\|/g, "/")} | ${classes.map(name => `\`.${name}\``).join(" ") || "-"} | ${variables.map(name => `\`${name}\``).join(" ") || "-"} |`);
    }
    return lines.join("\n") + "\n";
}

if (process.argv[1] && process.argv[1].endsWith("styling-docs.mjs")) {
    writeFileSync(join(root, "docs/styling.md"), buildStylingDocs());
    console.log("docs/styling.md written");
}
